def clean(s):
    s=re.sub(r'(?<=[А-Яа-яЁё])(?=\d)|(?<=\d)(?=[А-Яа-яЁё])',' ',s)
    return s.replace(':10',': 10').replace(',11',', 11').replace(',20',', 20')
def stamp(n):return f'{n//60}:{n%60:02d}'
def source(s):
    spans=[]
    if s.get('sourceLines'):
        a=s['sourceLines'];spans.append(f"исходник, строки {a['from']}–{a['to']}")
    if s.get('clarificationAnswers'):spans.append('уточнения автора, ответы '+', '.join(map(str,s['clarificationAnswers'])))
    return '; '.join(spans)
