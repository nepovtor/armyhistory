def wardrobe(n):
    if n<=24:return 'На герое волосы до стрижки, гражданская куртка и старые порванные джинсы чёрного цвета. Морская форма ещё не выдана.'
    if n==25:return 'Обмен вынужденный: герой не мог отказаться. Полученные брюки широкие, тёмно-синие, похожие по крою на брюки от кимоно. Переодевания в кадре нет.'
    if n<=32:return 'Волосы ещё не острижены. На герое прежняя гражданская куртка и широкие тёмно-синие брюки, полученные после обмена; старые джинсы чёрного цвета уже отданы.'
    if n==33:return 'Стрижка налысо происходит сейчас; гражданская одежда ещё не сдана. Лицо и пропорции прежние.'
    if n==34:return 'После душа выдают полный зимний комплект по ответу автора: три тельняшки, тёмно-синие роба и брюки, ремень с морской пряжкой, чёрная пилотка, четыре пары носков, ботинки, парадная форма с бескозыркой, бушлат и гюйс. Это вещи, а не всё одновременно надетое на человека.'
    if n<=40:return 'Герой обрит, в парадной морской форме, бескозырке и зимнем силуэте по R02/R04. Пилотка выдана, но в дорогу он отправился в бескозырке. Не переносить снег, мороз и фон фотографии R04 в тёплый Севастополь.'
    return 'Герой после стрижки спит на первом, нижнем ярусе. Точная одежда для сна автором не названа: показывай лицо и верх фигуры без новых костюмных деталей. Верхняя койка в Симферополе и нижняя в Севастополе — разные места.'

def quality(n):
    text=('Результат — одно цельное изображение и один момент события. Без панелей, коллажа, вариантов «до и после», повторных фигур одного человека, '
          'подписей, речевых пузырей и водяных знаков. Не добавляй номера частей, личные данные, лозунги, награды и неподтверждённые знаки различия. '
          'Руки, опоры ног и контакт с предметами анатомически убедительны; лица и важные детали не обрезаны.')
    if n>=34:
        return text+' Единственная разрешённая читаемая надпись — «Балтийский флот» на ленте бескозырки, если лента видна. Никаких случайных букв; при ошибке оставить ленту без текста для последующей ручной надписи.'
    return text+' Никакого читаемого текста внутри картинки.'

